import csv
import json
import numpy as np
import pyvista as pv
from fpdf import FPDF
from datetime import datetime
from pathlib import Path
from PIL import Image
import matplotlib.pyplot as plt
import os

class BaseExporter:
    def __init__(self, results, config):
        self.results = results
        self.config = config
        self.timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    def export(self, output_path):
        raise NotImplementedError("Les sous-classes doivent implémenter cette méthode")

class VTKExporter(BaseExporter):
    def export(self, output_path):
        points = np.array([point['position'] for point in self.results['coverage']])
        signal_strength = np.array([point['signal_strength'] for point in self.results['coverage']])
        cloud = pv.PolyData(points)
        cloud["signal_strength"] = signal_strength
        if 'scene_mesh' in self.config and self.config['scene_mesh']:
            scene_mesh = self.config['scene_mesh']
            merged = pv.MultiBlock([scene_mesh, cloud])
            # Correction : utiliser la bonne extension pour MultiBlock
            if not output_path.endswith(('.vtm', '.vtmb')):
                if '.' in output_path:
                    base_name = output_path.rsplit('.', 1)[0]
                else:
                    base_name = output_path
                correct_output_path = base_name + '.vtm'
                print(f"[DEBUG] VTKExporter: Changement d'extension de {output_path} à {correct_output_path}")
                output_path = correct_output_path
            merged.save(output_path)
        else:
            cloud.save(output_path)

class CSVExporter(BaseExporter):
    def export(self, output_path):
        with open(output_path, 'w', newline='') as csvfile:
            fieldnames = ['x', 'y', 'z', 'signal_strength_dBm']
            writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
            writer.writeheader()
            for point in self.results['coverage']:
                x, y, z = point['position']
                writer.writerow({
                    'x': x,
                    'y': y,
                    'z': z,
                    'signal_strength_dBm': point['signal_strength']
                })

class ImageExporter(BaseExporter):
    def export(self, output_path):
        z_level = self.config.get('z_level', 1.5)
        tolerance = 0.1
        plane_data = [
            p for p in self.results['coverage'] 
            if abs(p['position'][2] - z_level) < tolerance
        ]
        if not plane_data:
            raise ValueError(f"Aucune donnée disponible au niveau z={z_level}")
        x = [p['position'][0] for p in plane_data]
        y = [p['position'][1] for p in plane_data]
        signal = [p['signal_strength'] for p in plane_data]
        plt.figure(figsize=(10, 8))
        scatter = plt.scatter(x, y, c=signal, cmap='viridis', s=10)
        plt.colorbar(scatter, label='Signal Strength (dBm)')
        plt.title(f'RF Coverage at {z_level}m Height')
        plt.xlabel('X (m)')
        plt.ylabel('Y (m)')
        plt.grid(True)
        plt.savefig(output_path, dpi=300)
        plt.close()

class PDFReportExporter(BaseExporter):
    def export(self, output_path):
        pdf = FPDF()
        pdf.add_page()
        pdf.set_font("Arial", size=12)
        pdf.set_font_size(16)
        pdf.cell(200, 10, txt="RF Simulation Report", ln=True, align='C')
        pdf.ln(10)
        self._add_metadata_section(pdf)
        self._add_configuration_section(pdf)
        self._add_results_section(pdf)
        self._add_visualizations_section(pdf)
        pdf.set_y(-15)
        pdf.set_font_size(8)
        pdf.cell(0, 10, f"Generated by RF Simulator 3D on {datetime.now().strftime('%Y-%m-%d %H:%M')}", 0, 0, 'C')
        pdf.output(output_path)
    def _add_metadata_section(self, pdf):
        pdf.set_font_size(14)
        pdf.cell(200, 10, txt="Project Information", ln=True)
        pdf.set_font_size(12)
        metadata = self.config.get('metadata', {})
        pdf.cell(50, 10, txt="Project Name:", ln=0)
        pdf.cell(140, 10, txt=metadata.get('name', 'N/A'), ln=True)
        pdf.cell(50, 10, txt="Author:", ln=0)
        pdf.cell(140, 10, txt=metadata.get('author', 'N/A'), ln=True)
        pdf.cell(50, 10, txt="Description:", ln=0)
        pdf.multi_cell(140, 10, txt=metadata.get('description', ''))
        pdf.ln(5)
    def _add_configuration_section(self, pdf):
        pdf.set_font_size(14)
        pdf.cell(200, 10, txt="Simulation Configuration", ln=True)
        pdf.set_font_size(12)
        config_data = self.config.get('simulation_config', {})
        for key, value in config_data.items():
            pdf.cell(70, 10, txt=f"{key.replace('_', ' ').title()}:", ln=0)
            pdf.cell(120, 10, txt=str(value), ln=True)
        pdf.ln(5)
        pdf.set_font_size(14)
        pdf.cell(200, 10, txt="Antennas Configuration", ln=True)
        pdf.set_font_size(12)
        antennas = self.config.get('antennas', [])
        if antennas:
            headers = ["Type", "Position", "Frequency", "Power"]
            col_widths = [40, 60, 40, 40]
            pdf.set_font(style='B')
            for header, width in zip(headers, col_widths):
                pdf.cell(width, 10, txt=header, border=1, ln=0)
            pdf.ln()
            pdf.set_font(style='')
            for ant in antennas:
                pos = f"({ant['position']['x']}, {ant['position']['y']}, {ant['position']['z']})"
                pdf.cell(col_widths[0], 10, txt=ant['type'], border=1, ln=0)
                pdf.cell(col_widths[1], 10, txt=pos, border=1, ln=0)
                pdf.cell(col_widths[2], 10, txt=ant['frequency'], border=1, ln=0)
                pdf.cell(col_widths[3], 10, txt=str(ant['power_dbm']), border=1, ln=1)
        pdf.ln(10)
    def _add_results_section(self, pdf):
        pdf.set_font_size(14)
        pdf.cell(200, 10, txt="Simulation Results", ln=True)
        pdf.set_font_size(12)
        min_signal = min(p['signal_strength'] for p in self.results['coverage'])
        max_signal = max(p['signal_strength'] for p in self.results['coverage'])
        avg_signal = sum(p['signal_strength'] for p in self.results['coverage']) / len(self.results['coverage'])
        pdf.cell(70, 10, txt="Minimum Signal:", ln=0)
        pdf.cell(50, 10, txt=f"{min_signal:.2f} dBm", ln=True)
        pdf.cell(70, 10, txt="Maximum Signal:", ln=0)
        pdf.cell(50, 10, txt=f"{max_signal:.2f} dBm", ln=True)
        pdf.cell(70, 10, txt="Average Signal:", ln=0)
        pdf.cell(50, 10, txt=f"{avg_signal:.2f} dBm", ln=True)
        pdf.ln(10)
    def _add_visualizations_section(self, pdf):
        pdf.set_font_size(14)
        pdf.cell(200, 10, txt="Visualizations", ln=True)
        if 'image_path' in self.config and os.path.exists(self.config['image_path']):
            pdf.image(self.config['image_path'], x=50, w=100)
            pdf.cell(200, 10, txt="RF Coverage Map", ln=True, align='C')
            pdf.ln(5)
        if 'screenshot_path' in self.config and os.path.exists(self.config['screenshot_path']):
            pdf.image(self.config['screenshot_path'], x=50, w=100)
            pdf.cell(200, 10, txt="3D Visualization", ln=True, align='C')

class ExportManager:
    def __init__(self):
        self.exporters = {
            'vtk': VTKExporter,
            'csv': CSVExporter,
            'png': ImageExporter,
            'pdf': PDFReportExporter
        }
    def export(self, results, format, output_path, config=None):
        if format not in self.exporters:
            raise ValueError(f"Format non supporté: {format}")
        config = config or {}
        exporter = self.exporters[format](results, config)
        exporter.export(output_path)
    def batch_export(self, results, base_path, formats, config=None):
        config = config or {}
        results_paths = {}
        for fmt in formats:
            ext = fmt if fmt != 'pdf' else 'pdf'
            path = f"{base_path}.{ext}"
            self.export(results, fmt, path, config)
            results_paths[fmt] = path
        return results_paths
